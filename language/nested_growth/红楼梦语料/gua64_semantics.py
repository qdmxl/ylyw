# 重建: index -> 卦词条(按引擎二进制 index 排列)
GUA_BY_INDEX = {}   # int -> dict
NAME_INDEX = {}     # 卦名 -> engine index
for name, low, up, xiang, yi, zai in GUA_ENTRIES:
    idx = engine_index(low, up)
    assert 0 <= idx < N_STATE, (name, idx)
    assert idx not in GUA_BY_INDEX, f"index冲突 {idx} ({GUA_BY_INDEX[idx]['name']} vs {name})"
    # 确保载义项含自身卦名锚(单字卦名); 多字卦名取其核心字
    items = [it.strip() for it in zai.split(",") if it.strip()]
    if name not in items:
        head = name[0] if len(name) > 1 else name
        if head not in items:
            items.insert(0, name)
        zai = ",".join(items)
    GUA_BY_INDEX[idx] = {"seq": idx, "name": name, "up": up, "low": low,
                         "xiang": xiang, "yi": yi, "zai": zai}
    NAME_INDEX[name] = idx

# 补: 8经卦也应能按卦名查(即便名字带'小大'等, 已覆盖)

def gua_index(name: str) -> int:
    if name in NAME_INDEX:
        return NAME_INDEX[name]
    raise KeyError(name)

def gua_basis(idx: int) -> np.ndarray:
    v = np.zeros(N_STATE, dtype=complex)
    v[int(idx) % N_STATE] = 1.0
    return v

def gua_info(idx: int) -> dict:
    return GUA_BY_INDEX[int(idx) % N_STATE]

def find_gua_by_meaning(word: str) -> list:
    hits = []
    for idx, g in GUA_BY_INDEX.items():
        if word in g["zai"]:
            hits.append((g["name"], idx))
    return hits

