def engine_index(low_bg, up_bg):
    """下卦+上卦 → 引擎六爻二进制 index。"""
    y = list(T3[low_bg]) + list(T3[up_bg])
    idx = 0
    for b in reversed(y):
        idx = (idx << 1) | b
    return idx

