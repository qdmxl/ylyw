    print(f"64卦语义义项库(按引擎二进制 index): {len(GUA_BY_INDEX)} 卦")
    print(f"8经卦: ", {n: NAME_INDEX[n] for n in ['乾','坤','坎','离','震','巽','艮','兑']})
    print("\n=== 抽样(与引擎index对齐) ===")
    for nm in ["乾","坤","屯","蒙","坎","离","困","井","震","艮","兑","节","既济","未济"]:
        idx = NAME_INDEX[nm]
